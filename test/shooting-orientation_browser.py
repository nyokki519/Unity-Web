import os, json
from pathlib import Path
from playwright.sync_api import sync_playwright

base=os.environ.get('UNITY_URL','http://127.0.0.1:3482')
out=Path(os.environ.get('SHOOTING_QA_DIR','docs/shooting/qa/orientation-v1.4'))
out.mkdir(parents=True,exist_ok=True)
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path='/usr/bin/chromium',args=['--no-sandbox','--use-angle=swiftshader','--enable-unsafe-swiftshader'])
    context=browser.new_context(viewport={'width':390,'height':844},is_mobile=True,has_touch=True)
    page=context.new_page()
    errors=[]
    page.on('pageerror',lambda error:errors.append(str(error)))
    page.goto(base+'/shooting/index.html')
    page.wait_for_function('()=>!!window.SHOOTING',timeout=90000)
    page.locator('[data-do=quickstart]').click()
    page.wait_for_function('()=>SHOOTING.game?.tick>30',timeout=30000)
    page.set_viewport_size({'width':956,'height':440})
    page.locator('#rotate-notice').wait_for(state='visible',timeout=5000)
    page.screenshot(path=str(out/'landscape-guide-956x440.png'))
    assert page.evaluate('SHOOTING.paused')
    tick=page.evaluate('SHOOTING.game.tick')
    snapshot=page.evaluate('JSON.stringify(SHOOTING.game.snapshot())')
    page.keyboard.press('ArrowRight')
    page.mouse.click(50,50)
    assert page.evaluate("document.elementFromPoint(50,50)?.closest('#rotate-notice')!==null")
    page.wait_for_timeout(250)
    assert page.evaluate('SHOOTING.game.tick')==tick
    assert page.evaluate('JSON.stringify(SHOOTING.game.snapshot())')==snapshot
    stage=page.evaluate('SHOOTING.game.stage')
    page.evaluate("""()=>{SHOOTING.game.phase='stageclear';const dialog=document.querySelector('#overlay');dialog.innerHTML='<button data-do="next">next</button><button data-do="resume">resume</button>';dialog.hidden=false;dialog.querySelector('[data-do=next]').dispatchEvent(new MouseEvent('click',{bubbles:true}));}""")
    assert page.evaluate('SHOOTING.game.stage')==stage, 'next-stage action bypassed landscape guard'
    assert page.evaluate('SHOOTING.game.phase')=='stageclear'
    page.evaluate("""()=>{SHOOTING.game.phase='play';const dialog=document.querySelector('#overlay');dialog.innerHTML='<button data-do="resume" class="primary">resume</button>';dialog.hidden=false;}""")
    page.set_viewport_size({'width':390,'height':844})
    page.locator('#rotate-notice').wait_for(state='hidden',timeout=5000)
    assert page.evaluate('SHOOTING.paused')
    page.screenshot(path=str(out/'portrait-paused-390x844.png'))
    page.locator('[data-do=resume]').click()
    page.wait_for_function(f'()=>SHOOTING.game.tick>{tick+5}',timeout=10000)
    assert not errors,errors
    launch=context.new_page()
    launch.on('pageerror',lambda error:errors.append(str(error)))
    launch.goto(base+'/shooting/index.html')
    launch.wait_for_function('()=>!!window.SHOOTING',timeout=90000)
    launch.set_viewport_size({'width':844,'height':390})
    launch.locator('[data-do=quickstart]').click()
    launch.locator('#rotate-notice').wait_for(state='visible',timeout=5000)
    assert launch.evaluate('SHOOTING.game===null')
    assert launch.evaluate('document.querySelector("#app").inert')
    assert launch.evaluate('document.activeElement.id')=='rotate-notice'
    launch.set_viewport_size({'width':956,'height':440})
    launch.locator('#rotate-notice').wait_for(state='visible',timeout=5000)
    launch.set_viewport_size({'width':390,'height':844})
    launch.locator('#rotate-notice').wait_for(state='hidden',timeout=5000)
    assert not launch.evaluate('document.querySelector("#app").inert')
    assert launch.evaluate("document.activeElement.matches('[data-do=quickstart]')"), 'focus did not return to blocked launch action'
    launch.locator('[data-do=quickstart]').click()
    launch.wait_for_function('()=>SHOOTING.game?.tick>10',timeout=15000)
    launch.set_viewport_size({'width':956,'height':440})
    launch.locator('#rotate-notice').wait_for(state='visible',timeout=5000)
    launch.evaluate("""()=>document.querySelector('#overlay [data-do=abandon]').dispatchEvent(new MouseEvent('click',{bubbles:true}))""")
    assert launch.evaluate('SHOOTING.game===null')
    assert launch.locator('#rotate-notice').is_hidden(), 'orientation dialog remained over hangar after navigation'
    assert not launch.evaluate('document.querySelector("#app").inert')
    assert not launch.locator('#menu').is_hidden()
    assert not errors,errors
    launch.close()
    desktop=browser.new_page(viewport={'width':844,'height':390})
    desktop.on('pageerror',lambda error:errors.append(str(error)))
    desktop.goto(base+'/shooting/index.html')
    desktop.wait_for_function('()=>!!window.SHOOTING',timeout=90000)
    desktop.locator('[data-do=quickstart]').click()
    desktop.wait_for_function('()=>SHOOTING.game?.tick>10',timeout=15000)
    assert desktop.locator('#rotate-notice').is_hidden(), 'mouse-only desktop window was treated as a rotated phone'
    assert not desktop.evaluate('document.querySelector("#app").inert')
    desktop.close()
    resume=context.new_page()
    resume.on('pageerror',lambda error:errors.append(str(error)))
    checkpoint={"version":1,"gameVersion":"1.4.0","savedAt":1,"stage":0,"forceAutofire":True,"replay":{"version":1,"gameVersion":"1.4.0","options":{"seed":"rotation-resume","mode":"campaign","difficulty":"easy","stage":0,"ship":0,"weapon":0,"support":0,"runId":"rotation-resume"},"inputs":[[0,{"dx":0,"dy":0,"fire":True}]],"endTick":600}}
    resume.add_init_script("localStorage.setItem('unity-shooting-checkpoint-v1',"+json.dumps(json.dumps(checkpoint))+ ")")
    resume.goto(base+'/shooting/index.html')
    resume.wait_for_function('()=>!!window.SHOOTING',timeout=90000)
    resume.set_viewport_size({'width':956,'height':440})
    resume.locator('[data-do=resume-checkpoint]').click()
    resume.locator('#rotate-notice').wait_for(state='visible',timeout=5000)
    assert resume.evaluate('SHOOTING.game===null')
    assert resume.evaluate("!!localStorage.getItem('unity-shooting-checkpoint-v1')")
    resume.set_viewport_size({'width':390,'height':844})
    resume.locator('[data-do=resume-checkpoint]').click()
    resume.wait_for_function('()=>SHOOTING.game?.tick>600',timeout=15000)
    resume.close()
    restoring=context.new_page()
    restoring.on('pageerror',lambda error:errors.append(str(error)))
    restoring.goto(base+'/shooting/index.html')
    restoring.wait_for_function('()=>!!window.SHOOTING',timeout=90000)
    restoring.evaluate("""()=>{const replay={version:1,gameVersion:'1.4.0',options:{seed:'rotation-during-restore',mode:'campaign',difficulty:'easy',stage:0,ship:0,weapon:0,support:0,runId:'rotation-during-restore'},inputs:[[0,{dx:0,dy:0,fire:true}]],endTick:15000};SHOOTING.start({},replay,true,true);SHOOTING.game.player.invincible=1e6;}""")
    assert restoring.evaluate('SHOOTING.restoringCheckpoint')
    restoring.set_viewport_size({'width':956,'height':440})
    restoring.locator('#rotate-notice').wait_for(state='visible',timeout=5000)
    restore_tick=restoring.evaluate('SHOOTING.game.tick')
    restoring.wait_for_timeout(250)
    assert restoring.evaluate('SHOOTING.game.tick')==restore_tick
    restoring.set_viewport_size({'width':390,'height':844})
    restoring.locator('#rotate-notice').wait_for(state='hidden',timeout=5000)
    restoring.wait_for_function('()=>!SHOOTING.restoringCheckpoint',timeout=30000)
    assert restoring.evaluate('SHOOTING.paused')
    assert restoring.locator('[data-do=resume]').is_visible()
    restore_paused_tick=restoring.evaluate('SHOOTING.game.tick')
    restoring.locator('[data-do=resume]').click()
    restoring.wait_for_function(f'()=>SHOOTING.game.tick>{restore_paused_tick+5}',timeout=10000)
    restoring.close()
    replay=context.new_page()
    replay.on('pageerror',lambda error:errors.append(str(error)))
    replay.goto(base+'/shooting/index.html')
    replay.wait_for_function('()=>!!window.SHOOTING',timeout=90000)
    replay.evaluate("""()=>{const replay={version:1,gameVersion:'1.4.0',options:{seed:'rotation-replay',mode:'campaign',difficulty:'easy',stage:0,ship:0,weapon:0,support:0,runId:'rotation-replay'},inputs:[[0,{dx:0,dy:0,fire:true}]],endTick:12000};SHOOTING.start({},replay);SHOOTING.game.player.invincible=1e6;}""")
    replay.wait_for_function('()=>SHOOTING.game?.tick>10',timeout=10000)
    replay.set_viewport_size({'width':956,'height':440})
    replay.locator('#rotate-notice').wait_for(state='visible',timeout=5000)
    replay_tick=replay.evaluate('SHOOTING.game.tick')
    replay.wait_for_timeout(250)
    assert replay.evaluate('SHOOTING.game.tick')==replay_tick, 'replay advanced behind landscape notice'
    assert replay.evaluate('SHOOTING.paused'), 'replay did not enter paused state'
    assert replay.evaluate('document.querySelector("#app").inert'), 'underlying app remains keyboard interactive'
    assert replay.evaluate('document.activeElement.id')=='rotate-notice', 'focus was not moved to orientation dialog'
    replay.keyboard.press('Tab')
    replay.keyboard.press('ArrowRight')
    assert replay.evaluate('document.activeElement.id')=='rotate-notice', 'keyboard focus escaped orientation dialog'
    replay.set_viewport_size({'width':390,'height':844})
    replay.locator('#rotate-notice').wait_for(state='hidden',timeout=5000)
    replay_tick=replay.evaluate('SHOOTING.game.tick')
    replay.wait_for_timeout(250)
    assert replay.evaluate('SHOOTING.game.tick')==replay_tick, 'replay resumed without explicit user action'
    replay.locator('[data-do=resume]').click()
    replay.wait_for_function(f'()=>SHOOTING.game.tick>{replay_tick+5}',timeout=10000)
    replay.close()
    (out/'report.json').write_text(json.dumps({'landscapePaused':True,'tickStable':True,'portraitRequiresResume':True,'portraitResumes':True,'landscapeLaunchBlocked':True,'mouseDesktopLandscapeAllowed':True,'nextStageBlockedWhileLandscape':True,'checkpointResumePreservedUntilPortrait':True,'checkpointRestoreFreezesInLandscape':True,'restoreRequiresResume':True,'replayFreezesInLandscape':True,'replayRequiresExplicitResume':True,'orientationDialogOwnsFocus':True,'keyboardFocusTrapped':True,'appInertWhileRotated':True,'navigationHidesOrientationDialog':True,'errors':errors},indent=2))
    print('orientation guard pauses, preserves state and resumes in portrait')
    context.close()
    browser.close()
